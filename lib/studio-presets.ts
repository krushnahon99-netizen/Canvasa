let idCounter = 100
export function createElementId(prefix = 'el'): string {
  idCounter += 1
  return `${prefix}-${Date.now().toString(36)}-${idCounter}`
}

export function materializeTemplateElements(
  template: StudioTemplate,
  targetWidth: number,
  targetHeight: number
): CanvasElement[] {
  const sx = targetWidth / template.baseWidth
  const sy = targetHeight / template.baseHeight
  const uniform = Math.min(sx, sy)

  return template.elements.map((el) => {
    const id = createElementId(el.type)
    const scaledBase = {
      ...el,
      id,
      x: Math.round(el.x * sx),
      y: Math.round(el.y * sy),
      width: Math.max(20, Math.round(el.width * sx)),
      height: Math.max(8, Math.round(el.height * sy)),
    }
    if (scaledBase.type === 'text') {
      return {
        ...scaledBase,
        fontSize: Math.max(12, Math.round(scaledBase.fontSize * uniform)),
      }
    }
    if (scaledBase.type === 'shape') {
      return {
        ...scaledBase,
        cornerRadius: Math.round(scaledBase.cornerRadius * uniform),
      }
    }
    return {
      ...scaledBase,
      cornerRadius: Math.round(scaledBase.cornerRadius * uniform),
    }
  })
}

